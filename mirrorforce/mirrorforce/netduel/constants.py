# MSG_WIN reason byte (strings 1500+; ygopro.h reason_to_string)
#
# 0x00-0x04 are the engine's own endings.  Everything from 0x10 up is an
# alternate win condition a *card script* declares with ``Duel.Win(player,
# reason)`` -- the reason travels straight from Lua into ``core.win_reason``
# (``libduel.cpp`` Duel.Win -> ``field.h`` win_reason -> ``processor.cpp``
# MSG_WIN), so the core header never names them and neither does
# ``constant.lua``: each script defines the constant locally, and three do not
# even do that.  The names below are the ones the scripts use, scanned across
# ygopro-scripts; the three unnamed ones are named after their card.
